# Using math library to calculate distance of a mathematical problem
import math
x1 = float(input("Enter the first x coordinate"))
x2 = float(input("Enter the second x coordinate"))
y1 = float(input("Enter the first y coordinate"))
y2 = float(input("Enter the second y coordinate"))

distance = math.sqrt((x2 - x1)**2 + (y2 - y1)**2)
print("The distance between the two coordinates is: {distance}")
print("#the use of the library is to be more efficient when solving on code#")



